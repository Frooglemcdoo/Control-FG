static void Emit(FILE* out,const char* name,ID3DBlob* blob){
 fprintf(out,"inline const unsigned char %s[] = {",name);
 auto* p=static_cast<const unsigned char*>(blob->GetBufferPointer());
 for(size_t i=0;i<blob->GetBufferSize();++i)fprintf(out,"%s%u,",i%24==0?"\n":"",unsigned(p[i]));
 fprintf(out,"\n};\n");
}
