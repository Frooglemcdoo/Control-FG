"""Reconstruct current 3D lighting before the native temporal blend."""
import base64
import hashlib
import struct
from pathlib import Path
from dxbc_transform import transform_shex

SOURCE_SHA = '566dbe6c0340b6c8b68004cc57093be77fe2d3bace7b32dd16f1605ae9bf5f1d'

def generate(data):
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA:
        raise ValueError('Unrecognized native volume filter')

    def patch(words):
        def dst(reg, mask=15):
            return [0x100002 | (mask << 4), reg]
        def src(reg, swizzle=0xe4):
            return [0x100006 | (swizzle << 4), reg]
        def imm(value):
            return [0x4001, struct.unpack('<I', struct.pack('<f', value))[0]]
        def vec(values):
            return [0x4002] + [imm(v)[1] for v in values]
        def ins(op, *args):
            body = sum(args, [])
            return [((len(body) + 1) << 24) | op] + body

        assert words[48:50] == [0x02000068, 5]
        assert words[407] & 0x7ff == 72 and words[420] & 0x7ff == 72
        assert words[326] & 0x7ff == 14 and words[326] & 0x2000
        # r5 = unclamped prior UV, r6 = validity flags and temp,
        # r7 = current tap coordinate, r8/r9 = coefficient sums, r10 = tap.
        words[49] = 11
        prior = ins(14, dst(5, 3), src(1, 0x44), src(1, 0xff))
        prior += ins(29, dst(6, 3), src(5), imm(0))
        prior += ins(29, dst(5, 3), imm(1), src(5))
        prior += ins(1, dst(5, 3), src(5), src(6))
        prior += ins(1, dst(5, 1), src(5, 0), src(5, 0x55))
        prior += ins(49, dst(6, 1), imm(0), src(1, 0xff))
        prior += ins(1, dst(5, 1), src(5, 0), src(6, 0))
        # Keep the engine's camera-cut/depth-slice history weight, but reject
        # UV outside the old view instead of clamping it to the border.
        reject = ins(1, dst(1, 1), src(1, 0), src(5, 0))
        gather = ins(54, dst(8), imm(0)) + ins(54, dst(9), imm(0))
        # cb0[21].xy contains native inverse volume width/height.
        inverse = list(words[112:116])
        inverse[0] = (inverse[0] & ~0xff0) | (0x04 << 4)
        for x, y in ((-.5, -.5), (.5, -.5), (-.5, .5), (.5, .5)):
            gather += ins(54, dst(7), src(2, 0x34))
            gather += ins(50, dst(7, 3), vec((x, y, 0, 0)), inverse, src(2))
            for start, end, accumulator in ((407, 420, 8), (420, 433, 9)):
                sample = list(words[start:end])
                sample[1:3] = dst(10, 7 if accumulator == 8 else 15)
                sample[3:5] = src(7)
                # The first native texture is swizzled wxyz into .yzw.
                # Gather xyz directly, then write it back into .yzw below.
                sample[5] = (sample[5] & ~0xff0) | (0xe4 << 4)
                gather += sample
                mask = 7 if accumulator == 8 else 15
                gather += ins(50, dst(accumulator, mask), src(10), imm(.25), src(accumulator))
        gather += ins(54, dst(1, 14), src(8, 0x90))
        gather += ins(54, dst(2), src(9))
        # Apply backwards, preserving the audited native instruction offsets.
        words[407:433] = reject + gather
        words[326:326] = prior

    return transform_shex(data, patch)

def write_header(root):
    source = base64.b64decode((root / 'research/volume-filter-r344/native-filter.dxbc.b64').read_text())
    result = generate(source)
    out = root / 'build'
    out.mkdir(exist_ok=True)
    (out / 'volume-filter.dxbc').write_bytes(result)
    lines = ['#pragma once', '// Generated by tools/volume_filter.py.']
    for name, data in (('kVolumeNativeShader', source), ('kVolumeFilteredShader', result)):
        lines += ['inline constexpr unsigned char ' + name + '[] = {']
        lines += [','.join(map(str, data[i:i+24])) + ',' for i in range(0, len(data), 24)]
        lines += ['};']
    (root / 'src/volume_filter.generated.h').write_text('\n'.join(lines) + '\n')
    return source, result

if __name__ == '__main__':
    write_header(Path(__file__).resolve().parents[1])
