"""Exact, reversible input-isolation shaders for the captured character pixel shader."""
import base64,hashlib,struct,sys,tempfile
from pathlib import Path
from dxbc_transform import transform_shex
from dxbc_checksum import checksum
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'research/native-integration-audit/tools'))
from decode_dxbc import decode
SHA='bbdd044d5f91b2296297ce4b9efeb5ef72169906299084984595bd9c896b4cd9'
NAMES=['shadow-y-neutral','shadow-w-neutral','uniform-volume-rig','diffuse-buffer-off','specular-buffer-off','translucency-off']
def dst(r,mask):return [0x100002|(mask<<4),r]
def imm(v):return [0x4001,struct.unpack('<I',struct.pack('<f',v))[0]]
def src(r,swizzle):return [0x100006|(swizzle<<4),r]
def mov(d,s):return [((1+len(d)+len(s))<<24)|54]+d+s
# Insertions preserve ALL original instructions, declarations, output, and bindings.
PATCHES=[{3923:mov(dst(0,1),imm(1))},
         {3923:mov(dst(0,2),imm(1))},
         {837:mov(dst(6,14),imm(1))+mov(dst(5,1),src(5,0x55))},
         {502:mov(dst(2,7),imm(0))},
         {510:mov(dst(1,7),imm(0))},
         {1930:mov(dst(17,7),imm(0)),2825:mov(dst(19,7),imm(0)),3742:mov(dst(4,7),imm(0))}]
def generate(data,index):
    if hashlib.sha256(data).hexdigest()!=SHA:raise ValueError('Unknown character shader')
    def patch(words):
        for offset,insert in sorted(PATCHES[index].items(),reverse=True):words[offset:offset]=insert
    return transform_shex(data,patch)
def main():
    data=base64.b64decode((root/'research/character-surface-r346/native-character.dxbc.b64').read_text())
    assert hashlib.sha256(data).hexdigest()==SHA
    folder=root/'build';folder.mkdir(exist_ok=True)
    original=folder/'character-surface-native.dxbc';original.write_bytes(data);old=decode(original)
    shaders=[data]
    for n in range(6):
        result=generate(data,n);assert result[4:20]==checksum(result)
        p=folder/f'character-surface-{n}.dxbc';p.write_bytes(result);new=decode(p)
        assert old['bindings']==new['bindings'] and old['constant_buffers']==new['constant_buffers']
        # Removing inserted words recovers the entire native SHEX exactly.
        def words(b):
            for off in struct.unpack_from('<'+'I'*struct.unpack_from('<I',b,28)[0],b,32):
                if b[off:off+4]==b'SHEX':return list(struct.unpack_from('<'+'I'*(struct.unpack_from('<I',b,off+4)[0]//4),b,off+8))
        a=words(result);delta=0
        for offset,ins in sorted(PATCHES[n].items()):
            assert a[offset:offset+len(ins)]==ins
            del a[offset:offset+len(ins)]
        a[1]=len(a);assert a==words(data)
        shaders.append(result)
    try:generate(data[:-1],0)
    except ValueError:pass
    else:raise AssertionError('Bad shader admitted')
    lines=['#pragma once','// Generated by tools/character_surface.py; never applied outside TEST JESSE.']
    for i,b in enumerate(shaders):
        lines+=['inline constexpr unsigned char kCharacterSurface'+str(i)+'[] = {']
        lines+=[','.join(map(str,b[j:j+24]))+',' for j in range(0,len(b),24)];lines+=['};']
    lines+=['inline constexpr D3D12_SHADER_BYTECODE kCharacterSurfaceVariants[] = {']
    lines+=['{kCharacterSurface'+str(i)+',sizeof(kCharacterSurface'+str(i)+')},' for i in range(1,7)];lines+=['};']
    (folder/'character_surface.generated.h').write_text('\n'.join(lines)+'\n')
    print('PASS six exact character input-isolation shaders, unchanged bindings and full native instruction recovery')
if __name__=='__main__':main()
