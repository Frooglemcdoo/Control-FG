"""Exact, reversible input-isolation shaders for the captured character pixel shader."""
import base64,hashlib,struct,sys,tempfile
from pathlib import Path
from dxbc_transform import transform_shex
from dxbc_checksum import checksum
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'research/native-integration-audit/tools'))
from decode_dxbc import decode
SHA='bbdd044d5f91b2296297ce4b9efeb5ef72169906299084984595bd9c896b4cd9'
NAMES=['surface-normal','rig-off','unlit-albedo','flat-before-fog','flat-final','fog-off']
def dst(r,mask):return [0x100002|(mask<<4),r]
def imm(v):return [0x4001,struct.unpack('<I',struct.pack('<f',v))[0]]
def src(r,swizzle):return [0x100006|(swizzle<<4),r]
def mov(d,s):return [((1+len(d)+len(s))<<24)|54]+d+s
# Audited original instruction boundaries. All changes are temporary capture views.
def out(mask):return [0x102002|(mask<<4),0]
PATCHES=[
    # Decoded surface normal r2.xyw replaces bent-normal texture value r15.xyz.
    {1266:mov(dst(15,7),src(2,0x34))},
    # Both accumulated light-rig terms, before the two shadow masks are applied.
    {3915:mov(dst(5,7),imm(0))+mov(dst(2,7),imm(0))},
    # Textured material color after detail modulation, before any light composition.
    {609:mov(out(7),src(3,0xe4))+mov(out(8),imm(1))+[(1<<24)|62]},
    # Equal gray controls: same alpha, one traverses native fog and one bypasses it.
    {3953:mov(dst(0,7),imm(.18)),4751:mov(out(8),imm(1))},
    {4751:mov(out(7),imm(.18))+mov(out(8),imm(1))},
    # Neutralize analytical atmosphere AND participating-media composition.
    {4690:mov(dst(1,7),imm(1))+mov(dst(2,7),imm(0)),
     4737:mov(dst(1,7),imm(0))+mov(dst(1,8),imm(1))}
]
def generate(data,index,basic=False):
    if hashlib.sha256(data).hexdigest()!=(BASIC_SHA if basic else SHA):raise ValueError('Unknown character shader')
    def patch(words):
        for offset,insert in sorted(PATCHES[index].items(),reverse=True):
            if basic and offset>=609:offset-=57
            words[offset:offset]=insert
    return transform_shex(data,patch)
BASIC_SHA='0cd8a4b8144f1add1eac28edb815477ad7e3b42291735aa361e2f8e77b20bb96'
def main():
    data=base64.b64decode((root/'research/character-surface-r346/native-character.dxbc.b64').read_text())
    assert hashlib.sha256(data).hexdigest()==SHA
    folder=root/'build';folder.mkdir(exist_ok=True)
    original=folder/'character-surface-native.dxbc';original.write_bytes(data);old=decode(original)
    shaders=[data]
    for n in range(6):
        result=generate(data,n);assert result[4:20]==checksum(result)
        p=folder/f'character-surface-{n}.dxbc';p.write_bytes(result);new=decode(p)
        assert old['bindings']==new['bindings'] and old['constant_buffers']==new['constant_buffers']
        # Removing inserted words recovers the entire native SHEX exactly.
        def words(b):
            for off in struct.unpack_from('<'+'I'*struct.unpack_from('<I',b,28)[0],b,32):
                if b[off:off+4]==b'SHEX':return list(struct.unpack_from('<'+'I'*(struct.unpack_from('<I',b,off+4)[0]//4),b,off+8))
        a=words(result);delta=0
        for offset,ins in sorted(PATCHES[n].items()):
            assert a[offset:offset+len(ins)]==ins
            del a[offset:offset+len(ins)]
        a[1]=len(a);assert a==words(data)
        shaders.append(result)
    try:generate(data[:-1],0)
    except ValueError:pass
    else:raise AssertionError('Bad shader admitted')
    basic=base64.b64decode((root/'research/character-surface-r346/native-character-basic.dxbc.b64').read_text())
    assert hashlib.sha256(basic).hexdigest()==BASIC_SHA
    # Both families differ only in material-detail sampling ahead of the same input sites.
    original_basic=folder/'character-surface-basic.dxbc';original_basic.write_bytes(basic)
    basic_info=decode(original_basic)
    for offset in sorted({o for patch in PATCHES for o in patch}):
        a=next(i for i in old['instructions'] if i['dword']==offset)
        b=next(i for i in basic_info['instructions'] if i['dword']==offset-(57 if offset>=609 else 0))
        assert (a['name'],a['operands'])==(b['name'],b['operands'])
    shaders.append(basic)
    for n in range(6):
        result=generate(basic,n,True);assert result[4:20]==checksum(result)
        p=folder/f'character-surface-basic-{n}.dxbc';p.write_bytes(result)
        assert decode(p)['bindings']==basic_info['bindings']
        a=words(result)
        for offset,ins in sorted(PATCHES[n].items()):
            offset-=57 if offset>=609 else 0
            assert a[offset:offset+len(ins)]==ins
            del a[offset:offset+len(ins)]
        a[1]=len(a);assert a==words(basic)
        shaders.append(result)
    lines=['#pragma once','// Generated by tools/character_surface.py; never applied outside TEST JESSE.']
    for i,b in enumerate(shaders):
        lines+=['inline constexpr unsigned char kCharacterSurface'+str(i)+'[] = {']
        lines+=[','.join(map(str,b[j:j+24]))+',' for j in range(0,len(b),24)];lines+=['};']
    lines+=['inline constexpr D3D12_SHADER_BYTECODE kCharacterSurfaceVariants[] = {']
    lines+=['{kCharacterSurface'+str(i)+',sizeof(kCharacterSurface'+str(i)+')},' for i in range(1,7)];lines+=['};']
    lines+=['inline constexpr D3D12_SHADER_BYTECODE kCharacterSurfaceBasicVariants[] = {']
    lines+=['{kCharacterSurface'+str(i)+',sizeof(kCharacterSurface'+str(i)+')},' for i in range(8,14)];lines+=['};']
    (folder/'character_surface.generated.h').write_text('\n'.join(lines)+'\n')
    print('PASS six exact character stage-isolation shaders, unchanged bindings and full native instruction recovery')
if __name__=='__main__':main()
