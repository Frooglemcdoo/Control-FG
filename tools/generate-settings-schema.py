#!/usr/bin/env python3
"""Generate C++ metadata from the human-maintained settings catalog.

UI labels, defaults, IDs, ranges, choices and storage keys live in the JSON
catalog. This generated header contains no behavior; settings_catalog.h owns
renderer adapters. --check fails when a committed generated file is stale.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate(schema=None):
    if schema is None:
        schema = json.loads((ROOT / 'src/settings_schema.json').read_text())
    options, protocol = schema['options'], schema['protocol']
    assert 1 <= protocol['stateBits'] <= 30
    assert protocol['firstId'] <= protocol['handshakeId'] < protocol['endId']
    keys, ids, localization_keys = set(), set(), set()
    storage = set()
    for option in options:
        key, option_id = option['key'], option['id']
        assert key.isidentifier() and key not in keys, f'Duplicate/invalid key: {key}'
        assert protocol['firstId'] <= option_id < protocol['endId'] and option_id != protocol['handshakeId']
        assert option_id not in ids, f'Duplicate ID: {option_id}'
        assert type(option_id) is int and key.isascii()
        assert option['localizationKey'] not in localization_keys
        localization_keys.add(option['localizationKey'])
        assert option.get('presentation') in (None, 'slider')
        if option.get('presentation') == 'slider':
            assert option['type'] == 'choice'
        assert all(isinstance(name, str) and name.startswith('MENU_OPTIONS_') for name in option.get('nativeRequires', []))
        assert option.get('visibility') in (None, 'rtx40')
        assert option.get('capability') in (None, 'frameGeneration')
        assert option.get('defaultPolicy') in (None, 'supportedMultiplier')
        assert type(option['default']) is int
        keys.add(key); ids.add(option_id)
        values = [c['value'] for c in option.get('choices', [])]
        if option['type'] == 'choice':
            assert values and len(values) == len(set(values)) and option['default'] in values
        else:
            assert option['type'] == 'integer'
            assert all(type(option[k]) is int for k in ('min', 'max', 'step'))
            assert option['min'] <= option['default'] <= option['max'] and option['step'] > 0
            assert (option['default'] - option['min']) % option['step'] == 0
            values = [option['min'], option['max']]
        assert all(type(v) is int and 0 <= v < (1 << protocol['stateBits']) for v in values)
        if 'storage' in option:
            pair = tuple(option['storage'][k].casefold() for k in ('section', 'key'))
            assert pair not in storage, f'Duplicate storage key: {pair}'
            storage.add(pair)
    assert all(d['key'] in keys for o in options for d in o.get('requires', []))
    by_key = {option['key']: option for option in options}
    def visit(key, active):
        assert key not in active, f'Dependency cycle: {key}'
        for dependency in by_key[key].get('requires', []):
            source = by_key[dependency['key']]
            value = dependency['value']
            assert type(value) is int
            if source['type'] == 'choice':
                assert value in [choice['value'] for choice in source['choices']]
            else:
                assert source['min'] <= value <= source['max']
                assert (value - source['min']) % source['step'] == 0
            visit(source['key'], active | {key})
    for key in keys:
        visit(key, set())
    lines = ['// Generated by tools/generate-settings-schema.py. Edit settings_schema.json.',
             '#pragma once', '#include <cstddef>', '#include <initializer_list>',
             'namespace control_settings {', 'enum class Key {']
    lines += [f'    {o["key"]},' for o in options]
    lines += ['};', 'struct Dependency { Key key; unsigned value; };', 'struct Option {', '    Key key;', '    int id;',
              '    unsigned defaultValue, minimum, maximum, step;',
              '    std::initializer_list<unsigned> choices;',
              '    const wchar_t* section;', '    const wchar_t* storageKey;',
              '    std::initializer_list<Dependency> dependencies;', '};']
    for name in ['version','firstId','endId','handshakeId','stateBits']:
        lines.append(f'inline constexpr int k{name[0].upper()+name[1:]} = {protocol[name]};')
    lines.append('inline const Option kOptions[] = {')
    for o in options:
        choices = ', '.join(str(c['value']) for c in o.get('choices', []))
        storage = o.get('storage')
        section = 'L'+json.dumps(storage['section']) if storage else 'nullptr'
        storage_key = 'L'+json.dumps(storage['key']) if storage else 'nullptr'
        dependencies = ', '.join('{Key::%s, %d}' % (d['key'], d['value']) for d in o.get('requires', []))
        lines.append('    {Key::%s, %d, %d, %d, %d, %d, {%s}, %s, %s, {%s}},' %
                     (o['key'],o['id'],o['default'],o.get('min',0),o.get('max',0),o.get('step',1),choices,section,storage_key,dependencies))
    lines += ['};', 'inline constexpr std::size_t kOptionCount = sizeof(kOptions) / sizeof(kOptions[0]);', '}']
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'src/settings_schema.generated.h'
    text = generate()
    if args.check:
        assert output.read_text() == text, 'Settings schema is stale; run tools/generate-settings-schema.py'
    else:
        output.write_text(text)
